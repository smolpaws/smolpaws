"""Run with the pinned Python oracle venv; emits its Unicode casefold tables."""
import json
import unicodedata
from pathlib import Path

if unicodedata.unidata_version != "15.1.0":
    raise SystemExit("Use the pinned oracle Python with Unicode 15.1.0")
folds = {chr(i): chr(i).casefold() for i in range(0x110000) if chr(i).casefold() != chr(i)}
zeroes = [i for i in range(0x110000) if unicodedata.decimal(chr(i), None) == 0]
rows = list(folds.items())
out = ["// Generated by scripts/generate-git-casefold.py using pinned Python Unicode 15.1.0.",
       "// Full per-codepoint str.casefold mapping; do not substitute locale lowercasing.",
       "const folds: Readonly<Record<string, string>> = {"]
for start in range(0, len(rows), 12):
    out.append("  " + ", ".join(json.dumps(k, ensure_ascii=True) + ": " + json.dumps(v, ensure_ascii=True) for k, v in rows[start:start+12]) + ",")
out += ["};", "export function pythonCasefold(value: string): string {", "  return Array.from(value, char => folds[char] ?? char).join('');", "}",
        "export const PYTHON_DECIMAL_ZEROES: readonly number[] = " + json.dumps(zeroes) + ";", ""]
(Path(__file__).resolve().parent.parent / "src/gitCasefold.ts").write_text("\n".join(out))
