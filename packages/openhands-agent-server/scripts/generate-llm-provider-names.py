"""Generate the locked namespaces used by the source's conservative model filter."""
from __future__ import annotations

import argparse
import importlib.metadata
import json
import os
from pathlib import Path
import subprocess
import sys

os.environ['LITELLM_LOCAL_MODEL_COST_MAP'] = 'True'
os.environ['OPENHANDS_SUPPRESS_BANNER'] = '1'
parser = argparse.ArgumentParser()
parser.add_argument('source', type=Path)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
source = args.source.resolve()
root = Path(__file__).resolve().parent.parent
manifest = json.loads((root / 'vendor/openhands-agent/transpile/upstream.json').read_text())
commit = subprocess.check_output(['git', '-C', str(source), 'rev-parse', 'HEAD'], text=True).strip()
if commit != manifest['commit']:
    raise SystemExit('Source checkout must match the canonical vendored Python pin')
if subprocess.check_output(['git', '-C', str(source), 'status', '--porcelain'], text=True).strip():
    raise SystemExit('Source checkout must be clean')
sys.path[:0] = [str(source / name) for name in ('openhands-sdk', 'openhands-tools', 'openhands-workspace')]
from openhands.sdk.llm.utils import unverified_models  # noqa: E402
if Path(unverified_models.__file__).resolve() != source / 'openhands-sdk/openhands/sdk/llm/utils/unverified_models.py':
    raise SystemExit('Imported model namespace source is not the pinned checkout')
metadata = {'commit': commit, 'litellm': importlib.metadata.version('litellm'), 'source': 'openhands-sdk/openhands/sdk/llm/utils/unverified_models.py::_get_litellm_provider_names'}
output = '// Generated by scripts/generate-llm-provider-names.py. Do not edit.\n'
output += 'export const MODEL_PROVIDER_NAMES_SOURCE = ' + json.dumps(metadata, indent=2) + ' as const;\n\n'
output += 'export const MODEL_PROVIDER_NAMES: readonly string[] = ' + json.dumps(sorted(unverified_models._get_litellm_provider_names()), indent=2) + ';\n'
target = root / 'src/llmProviderNames.ts'
if args.check:
    if not target.exists() or target.read_text() != output:
        raise SystemExit('Provider namespace catalog differs from pinned source')
else:
    target.write_text(output)
print(f"{'Verified' if args.check else 'Generated'} provider namespaces at {commit}")
